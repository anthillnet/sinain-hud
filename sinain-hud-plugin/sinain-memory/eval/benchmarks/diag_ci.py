"""diag_ci.py — T1-DETERMINISM measurement discipline (eval-infra, NOT a memory
change; production path untouched).

A single LongMemEval run is a noisy point estimate: distillation is ~70%
non-deterministic run-to-run (byte-determinism is unachievable single-pass), so a
bare "27/36" hides a wide interval. This reports the score WITH a bootstrap
confidence interval over questions, plus a per-category breakdown and a
support-survival summary, so we stop tuning against single-run fog and can tell a
real gain from noise.

Deterministic bootstrap (fixed integer resampling, no RNG dependence on wall
clock) so the CI itself is reproducible.

Usage:
  python3 -m eval.benchmarks.diag_ci <results_dir> [n_boot]
Emits stdout + <results_dir>/ci_report.md
"""
import json
import os
import sys


def _load(results_dir: str) -> dict[str, dict]:
    """qid -> last entry (a re-run appends; last per id wins)."""
    path = os.path.join(results_dir, "longmemeval_progress.jsonl")
    last: dict[str, dict] = {}
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        last[r["id"]] = r
    return last


def _label(r: dict) -> int:
    a = r.get("answers", {}).get("sinain-memory", {})
    v = a.get("paper_label")
    if v is None:
        v = a.get("score") or 0
    return 1 if float(v or 0) >= 1 else 0


def _bootstrap_ci(labels: list[int], n_boot: int = 2000, alpha: float = 0.05) -> tuple[float, float, float]:
    """Deterministic percentile bootstrap over questions. Resampling indices are
    generated by a fixed linear-congruential sequence seeded by 0 so the interval
    is reproducible (Math.random/Date are unavailable / forbidden anyway)."""
    n = len(labels)
    if n == 0:
        return (0.0, 0.0, 0.0)
    mean = sum(labels) / n
    # LCG (Numerical Recipes constants) → deterministic pseudo-resampling
    state = 12345
    def _next():
        nonlocal state
        state = (1664525 * state + 1013904223) & 0xFFFFFFFF
        return state
    means = []
    for _ in range(n_boot):
        s = 0
        for _ in range(n):
            s += labels[_next() % n]
        means.append(s / n)
    means.sort()
    lo = means[int((alpha / 2) * n_boot)]
    hi = means[int((1 - alpha / 2) * n_boot) - 1]
    return (mean, lo, hi)


def main():
    rd = sys.argv[1]
    n_boot = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    last = _load(rd)
    qids = sorted(last)
    labels = [_label(last[q]) for q in qids]
    n = len(labels)
    p = sum(labels)
    mean, lo, hi = _bootstrap_ci(labels, n_boot)
    lines = []
    lines.append(f"# CI report — {os.path.basename(rd.rstrip('/'))}")
    lines.append(f"score: **{p}/{n}** = {mean:.3f}  95% bootstrap CI [{lo:.3f}, {hi:.3f}]"
                 f"  ≈ [{round(lo*n)}, {round(hi*n)}]/{n}")
    # per-category
    cats: dict[str, list[int]] = {}
    for q in qids:
        c = last[q].get("category", "?")
        cats.setdefault(c, []).append(_label(last[q]))
    lines.append("\n| category | pass/total |")
    lines.append("|---|---|")
    for c in sorted(cats):
        cl = cats[c]
        lines.append(f"| {c} | {sum(cl)}/{len(cl)} |")
    # fails
    fails = [q for q in qids if _label(last[q]) == 0]
    lines.append(f"\nFAILS ({len(fails)}): {fails}")
    out = "\n".join(lines)
    print(out)
    open(os.path.join(rd, "ci_report.md"), "w").write(out + "\n")


if __name__ == "__main__":
    main()
